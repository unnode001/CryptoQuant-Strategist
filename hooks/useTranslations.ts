type TranslationKeyWithParams = 'fetchSuccess' | 'fetchError' | 'dataLoadedInfo' | 'providerNotConfigured';

type RegularTranslationKey = Exclude<keyof typeof translations.en, TranslationKeyWithParams>;

interface TranslationsContextType {
  language: 'en' | 'zh';
  setLanguage: (language: 'en' | 'zh') => void;
  t: (key: RegularTranslationKey | TranslationKeyWithParams, params?: Record<string, string>) => string;
}

const TranslationsContext = createContext<TranslationsContextType | undefined>(undefined);

export const TranslationsProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguage] = useState<'en' | 'zh'>('zh');

  const t = useMemo(() => (key: any, params?: Record<string, string>): string => {
    let translation = translations[language][key as keyof typeof translations.en] || translations.en[key as keyof typeof translations.en];
    if (params) {
      Object.keys(params).forEach(paramKey => {
        translation = translation.replace(`{${paramKey}}`, params[paramKey]);
      });
    }
    return translation;
  }, [language]);
  
  return React.createElement(
    TranslationsContext.Provider,
    { value: { language, setLanguage, t } },
    children
  );
};

export const useTranslations = (): TranslationsContextType => {
  const context = useContext(TranslationsContext);
  if (context === undefined) {
    throw new Error('useTranslations must be used within a TranslationsProvider');
  }
  return context;
};
export type TranslationKey = keyof typeof translations.en;